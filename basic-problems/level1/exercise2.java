public class Main{
    static int add (int num1, int num2){
        return num1 + num2;
    }
    static int sub(int num1 , int num2){
        return num1  - num2;
    }
    static int multiply(int  num1 , int num2){
        return num1 * num2;
    }
    static int divition (int num1, int num2){
        return num1 / num2;
    }

    public static void main(String[] args){
        System.out.println(add(12,10));
        System.out.println(sub(10,10));
        System.out.println(multiply(2,2));
        System.out.println(divition(2,2));
    }
}

